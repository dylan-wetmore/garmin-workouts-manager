#!/usr/bin/env python3
"""Generate gwm/exercises.py from the Garmin FIT SDK exercise enums.

Garmin Connect's strength-workout steps carry `category` and `exerciseName`
string enums (e.g. SQUAT / BARBELL_BACK_SQUAT). The authoritative list of valid
pairs is the FIT SDK's `exercise_category` enum plus one `<category>_exercise_name`
enum per category. This script reads them and writes a static map so the tool has
no FIT-SDK runtime dependency.

Regenerate when the SDK updates:

    pip install garmin-fit-sdk
    python scripts/generate_exercises.py
"""

from __future__ import annotations

from pathlib import Path

from garmin_fit_sdk import Profile

OUT = Path(__file__).resolve().parent.parent / "gwm" / "exercises.py"
SKIP = {"invalid", "unknown"}


def build_map() -> dict[str, list[str]]:
    types = Profile["types"]
    categories = types["exercise_category"]
    result: dict[str, list[str]] = {}
    for _id, cat in categories.items():
        if cat in SKIP:
            continue
        names = types.get(f"{cat}_exercise_name")
        if not names:
            continue
        valid = sorted({n.upper() for n in names.values() if n not in SKIP})
        if valid:
            result[cat.upper()] = valid
    return result


def main() -> None:
    ex = build_map()
    total = sum(len(v) for v in ex.values())
    lines = [
        '"""Valid Garmin strength exercise (category -> names).',
        "",
        "AUTO-GENERATED by scripts/generate_exercises.py from the Garmin FIT SDK.",
        "Do not edit by hand; regenerate instead.",
        f"Categories: {len(ex)}  Names: {total}",
        '"""',
        "",
        "EXERCISES: dict[str, frozenset[str]] = {",
    ]
    for cat in sorted(ex):
        names = ", ".join(repr(n) for n in ex[cat])
        lines.append(f"    {cat!r}: frozenset({{{names}}}),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} — {len(ex)} categories, {total} names")


if __name__ == "__main__":
    main()
